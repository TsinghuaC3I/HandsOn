"""Convert Rayan's licensed mixer surfaces; create only invisible colliders.

No visible primitive or newly modeled surface is generated by this build.
"""
from pathlib import Path
import hashlib
import json
import os
import shutil
import numpy as np
import trimesh
from pxr import Gf, Sdf, Usd, UsdGeom, UsdPhysics, UsdShade, Vt
from asset_source import TASK_DIR, read_source
from panel_collision import derive_panel_colliders

ROOT = TASK_DIR.parents[2]
OUTPUT = ROOT / "handson/handson/sim/envs/usd/eval_gen05_set_mixer_knobs"
SOURCE = TASK_DIR / "source/audio_mixer_gltf"
ROTATE = np.array([[0., 0., -1.], [-1., 0., 0.], [0., 1., 0.]])
PANEL_SCALE = 0.0066
ROOT_HOME = [-0.14, 0.0, 0.915]
CENTERS_XY = {"left": [0.0, 0.135], "right": [0.0, -0.135]}
GRIP_SOURCE = "Cylinder098"
CLEAR_RADIUS = 0.062


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def geometry_only(parts):
    return trimesh.util.concatenate([
        trimesh.Trimesh(vertices=p.vertices, faces=p.faces, process=False) for p in parts])


def stage(path):
    s = Usd.Stage.CreateNew(str(path))
    UsdGeom.SetStageMetersPerUnit(s, 1.0)
    UsdGeom.SetStageUpAxis(s, "Z")
    root = UsdGeom.Xform.Define(s, "/Asset")
    s.SetDefaultPrim(root.GetPrim())
    return s


def materials(s, data):
    result = {}
    for item in data["materials"]:
        name = item["name"]
        path = f"/Asset/Materials/{name}"
        mat = UsdShade.Material.Define(s, path)
        shader = UsdShade.Shader.Define(s, path + "/Surface")
        shader.CreateIdAttr("UsdPreviewSurface")
        pbr = item.get("pbrMetallicRoughness", {})
        shader.CreateInput("diffuseColor", Sdf.ValueTypeNames.Color3f).Set(
            Gf.Vec3f(*pbr.get("baseColorFactor", [1., 1., 1., 1.])[:3]))
        shader.CreateInput("roughness", Sdf.ValueTypeNames.Float).Set(pbr.get("roughnessFactor", 1.))
        shader.CreateInput("metallic", Sdf.ValueTypeNames.Float).Set(pbr.get("metallicFactor", 1.))
        reader = UsdShade.Shader.Define(s, path + "/UV")
        reader.CreateIdAttr("UsdPrimvarReader_float2")
        reader.CreateInput("varname", Sdf.ValueTypeNames.Token).Set("st")
        for key, spec, factor in [
            ("diffuseColor", pbr.get("baseColorTexture"), [1., 1., 1.]),
            ("emissiveColor", item.get("emissiveTexture"), item.get("emissiveFactor", [0., 0., 0.])),
        ]:
            if spec is None:
                continue
            image_id = data["textures"][spec["index"]]["source"]
            uri = data["images"][image_id]["uri"]
            tex = UsdShade.Shader.Define(s, path + "/" + key)
            tex.CreateIdAttr("UsdUVTexture")
            tex.CreateInput("file", Sdf.ValueTypeNames.Asset).Set(Sdf.AssetPath(uri))
            tex.CreateInput("sourceColorSpace", Sdf.ValueTypeNames.Token).Set("sRGB")
            tex.CreateInput("scale", Sdf.ValueTypeNames.Float4).Set(Gf.Vec4f(*factor, 1.))
            tex.CreateInput("st", Sdf.ValueTypeNames.Float2).ConnectToSource(reader.ConnectableAPI(), "result")
            tex.CreateOutput("rgb", Sdf.ValueTypeNames.Float3)
            shader.CreateInput(key, Sdf.ValueTypeNames.Color3f).ConnectToSource(tex.ConnectableAPI(), "rgb")
        mat.CreateSurfaceOutput().ConnectToSource(shader.ConnectableAPI(), "surface")
        result[name] = mat
    return result


def author_mesh(s, path, mesh, material=None, collision=False, source_name=""):
    shape = UsdGeom.Mesh.Define(s, path)
    shape.CreatePointsAttr(Vt.Vec3fArray.FromNumpy(mesh.vertices.astype(np.float32)))
    shape.CreateFaceVertexCountsAttr(Vt.IntArray.FromNumpy(np.full(len(mesh.faces), 3, dtype=np.int32)))
    shape.CreateFaceVertexIndicesAttr(Vt.IntArray.FromNumpy(mesh.faces.astype(np.int32).ravel()))
    shape.CreateSubdivisionSchemeAttr("none")
    shape.CreateDoubleSidedAttr(True)
    shape.CreateExtentAttr(Vt.Vec3fArray.FromNumpy(mesh.bounds.astype(np.float32)))
    prim = shape.GetPrim()
    prim.SetCustomDataByKey("handson:sourceGroup", source_name)
    prim.SetCustomDataByKey("handson:geometryRole", "collision" if collision else "visual")
    if collision:
        UsdPhysics.CollisionAPI.Apply(prim)
        UsdPhysics.MeshCollisionAPI.Apply(prim).CreateApproximationAttr().Set("convexHull")
        shape.CreateVisibilityAttr().Set("invisible")
    else:
        shape.CreateNormalsAttr(Vt.Vec3fArray.FromNumpy(mesh.vertex_normals.astype(np.float32)))
        shape.SetNormalsInterpolation("vertex")
        uv = mesh.visual.uv
        if uv is not None:
            # trimesh exposes bottom-origin texture UVs; USD uses the same convention.
            st = UsdGeom.PrimvarsAPI(shape).CreatePrimvar("st", Sdf.ValueTypeNames.TexCoord2fArray, "vertex")
            st.Set(Vt.Vec2fArray.FromNumpy(uv.astype(np.float32)))
        UsdShade.MaterialBindingAPI.Apply(prim).Bind(material)


def limited_hull(mesh, directions=210):
    """An inner convex approximation using actual source support vertices."""
    k = np.arange(directions)
    z = 1.0 - 2.0 * (k + 0.5) / directions
    phi = k * np.pi * (3.0 - np.sqrt(5.0))
    dirs = np.column_stack([np.sqrt(1-z*z)*np.cos(phi), np.sqrt(1-z*z)*np.sin(phi), z])
    initial = trimesh.convex.convex_hull(mesh.vertices)
    # Preserve large sloped faces (especially the control deck) in addition
    # to uniformly sampled directions. There are at most 252 support points.
    important = initial.face_normals[np.argsort(initial.area_faces)[-36:]]
    dirs = np.vstack([dirs, np.eye(3), -np.eye(3), important])
    selected = np.unique(np.argmax(initial.vertices @ dirs.T, axis=0))
    return trimesh.convex.convex_hull(initial.vertices[selected])



def build():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    assert digest(TASK_DIR / "source_archives/audio-mixer.zip") == "402bbe68c91b5dcf0579b298bfdf2c10416e44ab4421718cab135f5b3c3b201e"
    assert digest(TASK_DIR / "source_archives/audio_mixer_gltf.zip") == "e69015a291d60f5d1f23e43759efb4c3ef727208a5065dbac7ef19c0c9f3f5e0"
    groups, source_report = read_source()
    data = json.loads((SOURCE / "scene.gltf").read_text())
    for item in data["images"]:
        target = OUTPUT / item["uri"]
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(SOURCE / item["uri"], target)
    shutil.copyfile(SOURCE / "license.txt", OUTPUT / "SOURCE_LICENSE.txt")
    body_source = geometry_only(groups["Box016"])
    source_origin = body_source.bounds.mean(axis=0)
    source_origin[1] = body_source.bounds[0, 1]
    transform = np.eye(4)
    transform[:3, :3] = PANEL_SCALE * ROTATE
    transform[:3, 3] = -PANEL_SCALE * ROTATE @ source_origin + np.array([0., 0., -0.025])
    body = body_source.copy().apply_transform(transform)
    print("Loaded and matched source surfaces", flush=True)

    grip_source = geometry_only(groups[GRIP_SOURCE])
    normals = grip_source.face_normals
    mask = normals[:, 1] > 0.9
    axis = (normals[mask] * grip_source.area_faces[mask, None]).sum(axis=0)
    axis /= np.linalg.norm(axis)
    align = trimesh.geometry.align_vectors(axis, [0., 0., 1.])
    aligned = grip_source.copy().apply_transform(align)
    pivot = aligned.bounds.mean(axis=0)
    pivot[2] = aligned.bounds[0, 2]
    radial_extent = np.linalg.norm(aligned.vertices[:, :2] - pivot[:2], axis=1).max()
    scale = np.array([0.055 / (2 * radial_extent)] * 2 + [0.045 / aligned.extents[2]])
    grip_transform = np.diag([*scale, 1.]) @ np.array([
        [1., 0., 0., -pivot[0]], [0., 1., 0., -pivot[1]],
        [0., 0., 1., -pivot[2]], [0., 0., 0., 1.],
    ]) @ align
    grip = grip_source.copy().apply_transform(grip_transform)
    # Keep the original tilted panel normal, rather than floating an upright
    # knob above the inclined panel. Joint local Z follows this mount normal.
    mount_rotation = trimesh.geometry.align_vectors([0., 0., 1.], ROTATE @ axis)
    mount_quaternion = trimesh.transformations.quaternion_from_matrix(mount_rotation).tolist()
    centers = {}
    for side, xy in CENTERS_XY.items():
        origin = np.array([*xy, 1.])
        hit, _, _ = body.ray.intersects_location([origin], [[0., 0., -1.]], multiple_hits=True)
        assert len(hit), "Knob mount misses the downloaded enclosure"
        surface_z = float(hit[:, 2].max())
        # A two-millimeter physical mount gap avoids authored parent/child
        # intersection; no phantom support sleeve is added.
        centers[side] = [*xy, surface_z + 0.002]

    fixed = {}
    removed = []
    for name, parts in groups.items():
        if not parts:
            continue  # OBJ groups containing guide lines only.
        converted = [p.copy().apply_transform(transform) for p in parts]
        bounds = geometry_only(converted).bounds
        if name != "Box016" and any(
            np.linalg.norm(np.maximum(np.maximum(bounds[0, :2] - xy, np.array(xy) - bounds[1, :2]), 0.)) < CLEAR_RADIUS
            for xy in CENTERS_XY.values()
        ):
            removed.append(name)
        else:
            fixed[name] = converted
    visual_stage = stage(OUTPUT / "mixer_fixed_visual.usda")
    mats = materials(visual_stage, data)
    for name, parts in fixed.items():
        for i, part in enumerate(parts):
            author_mesh(visual_stage, f"/Asset/{name}_{i}", part, mats[part.visual.material.name], source_name=name)
    visual_stage.GetRootLayer().Save()
    knob_stage = stage(OUTPUT / "knob_visual.usda")
    mats = materials(knob_stage, data)
    for i, original in enumerate(groups[GRIP_SOURCE]):
        part = original.copy().apply_transform(grip_transform)
        normal = original.vertex_normals @ np.linalg.inv(grip_transform[:3, :3])
        normal /= np.maximum(np.linalg.norm(normal, axis=1)[:, None], 1e-12)
        part.vertex_normals = normal
        author_mesh(knob_stage, f"/Asset/{GRIP_SOURCE}_{i}", part, mats[part.visual.material.name], source_name=GRIP_SOURCE)
    knob_stage.GetRootLayer().Save()
    print("Source visual assets exported; decomposing enclosure collision", flush=True)
    hulls, panel_pockets = derive_panel_colliders(body, limited_hull)
    (TASK_DIR / "evidence/source_panel_pockets.json").write_text(json.dumps(panel_pockets, indent=2) + "\n")
    collision_parts = [(f"enclosure_{i}", h, "Box016") for i, h in enumerate(hulls)]
    for name, parts in fixed.items():
        if name == "Box016":
            continue
        control = geometry_only(parts)
        if min(control.extents) > 0.00015:
            collision_parts.append((name, limited_hull(control), name))
    collision_stage = stage(OUTPUT / "mixer_fixed_collision.usda")
    for name, mesh, source_name in collision_parts:
        author_mesh(collision_stage, "/Asset/" + name, mesh, collision=True, source_name=source_name)
    collision_stage.GetRootLayer().Save()
    knob_hull = limited_hull(grip)
    knob_hull.density = 0.09 / knob_hull.volume
    knob_collision_stage = stage(OUTPUT / "knob_collision.usda")
    author_mesh(knob_collision_stage, "/Asset/grip", knob_hull, collision=True, source_name=GRIP_SOURCE)
    knob_collision_stage.GetRootLayer().Save()
    inertia, principal = np.linalg.eigh(knob_hull.moment_inertia)
    if np.linalg.det(principal) < 0:
        principal[:, 0] *= -1
    principal4 = np.eye(4)
    principal4[:3, :3] = principal
    geometry = {
        "root_home_m": ROOT_HOME, "knob_centers_m": centers,
        "knob_orientation_wxyz": mount_quaternion,
        "knob_com_m": knob_hull.center_mass.tolist(),
        "knob_diagonal_inertia_kg_m2": inertia.tolist(),
        "knob_principal_axes_wxyz": trimesh.transformations.quaternion_from_matrix(principal4).tolist(),
        "knob_mass_kg": 0.09, "base_mass_kg": 2.4,
        "knob_local_bounds_m": grip.bounds.tolist(), "fixed_bounds_m": body.bounds.tolist(),
        "source_knob_axis": axis.tolist(), "source_to_fixed_transform": transform.tolist(),
        "source_to_knob_transform": grip_transform.tolist(),
        "whole_panel_uniform_scale": PANEL_SCALE, "grip_radial_axial_scales": scale.tolist(),
        "grip_max_swept_diameter_m": 0.055, "grip_axial_height_m": 0.045,
        "knob_spacing_m": 0.27, "mount_vertical_clearance_m": 0.002,
        "cleared_control_radius_m": CLEAR_RADIUS,
        "removed_source_controls": removed, "kept_source_groups": list(fixed),
        "source_panel_pockets": panel_pockets,
        "enclosure_convex_parts": len(hulls), "fixed_collision_parts": len(collision_parts),
        "knob_collision_vertices": len(knob_hull.vertices),
    }
    credit = (SOURCE / "license.txt").read_text()
    (OUTPUT / "ATTRIBUTION.md").write_text(
        "# GEN6 source attribution\n\n" + credit +
        "\n## Modifications\n\nConverted the original surfaces to USD; retained source materials and texture UVs. "
        "Normalized the enclosure uniformly to meters. Reused Cylinder098 for two independently jointed knobs; "
        "aligned its measured axis and adjusted radial/axial scale to a 55 mm maximum swept diameter and 45 mm height. "
        "Removed surrounding source controls within the recorded hand-clearance areas. "
        "Derived invisible convex collision from these source surfaces. No new visible geometry was modeled.\n")
    files = {}
    for p in OUTPUT.rglob('*'):
        if p.is_file() and p.name not in {'asset_manifest.json', 'README.md'}:
            files[p.relative_to(OUTPUT).as_posix()] = digest(p)
    manifest = {
        "task_id": "GEN6", "task_name": "eval_gen05_set_mixer_knobs",
        "source": {**data['asset']['extras'], "url": data['asset']['extras']['source'],
                   "archives": {p.name: digest(p) for p in (TASK_DIR / 'source_archives').glob('*.zip')}},
        "source_match": source_report, "geometry": geometry, "files": files,
        "live_acceptance": "pending", "collider_surface_audit": "pending",
    }
    (OUTPUT / "asset_manifest.json").write_text(json.dumps(manifest, indent=2) + '\n')
    (TASK_DIR / "evidence/asset_build.json").write_text(json.dumps(manifest, indent=2) + '\n')
    print(json.dumps(geometry, indent=2), flush=True)
    return manifest


if __name__ == '__main__':
    build()
